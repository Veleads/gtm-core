// gtm sync: copies the kit of the installed core version into the project repo.
// .gtm/ and AGENTS.md are owned by core: regenerated on every sync, never edited by hand.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { parse } from "yaml";
import { isGitHubHandle } from "@gtm/schemas";
import { dirname, join } from "node:path";
import { walk } from "../fsutil.ts";
import { GTM_VERSION, KIT_DIR, PACKAGE_NAME } from "../paths.ts";

const SHIPPED_DIRS = ["skills", "templates", "providers", "schemas", "guides"];

const CODEOWNERS = join(".github", "CODEOWNERS");
const BLOCK_START = "# BEGIN gtm: generated by `gtm sync` from project.yaml → owners.approver. Edit owners there, not here.";
const BLOCK_END = "# END gtm";

/**
 * .github/CODEOWNERS with the gtm block for the current approver (GitHub mode only). Lines outside the
 * block are kept. Returns null when there is nothing to write (no file and no GitHub approver).
 */
export function expectedCodeowners(root: string): string | null {
  const projectFile = join(root, "project.yaml");
  const approver = existsSync(projectFile) ? parse(readFileSync(projectFile, "utf8"))?.owners?.approver : undefined;
  const path = join(root, CODEOWNERS);
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  const outside = current.replace(new RegExp(`\\n?${BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${BLOCK_END}\\n?`), "\n").trim();
  const block = isGitHubHandle(approver)
    ? [BLOCK_START, `/context/icp.yaml ${approver}`, `/context/signals.yaml ${approver}`, `/campaigns/*/copy.md ${approver}`, BLOCK_END].join("\n")
    : "";
  const next = [outside, block].filter(Boolean).join("\n\n");
  if (!next) return current ? "" : null;
  return `${next}\n`;
}

function agentsMd(): string {
  const header =
    `<!-- GENERATED by \`gtm sync\` from ${PACKAGE_NAME} v${GTM_VERSION}. Do not edit: it is overwritten on upgrade.\n` +
    `     Project-specific rules go in PROJECT.md. Process changes go to the Veleads/gtm-core repo. -->\n\n`;
  return header + readFileSync(join(KIT_DIR, "AGENTS.md"), "utf8").replaceAll("{{GTM_VERSION}}", GTM_VERSION);
}

/** Every core-owned file in a project repo, keyed by path relative to the repo root. */
export function expectedFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const dir of SHIPPED_DIRS) {
    for (const rel of walk(join(KIT_DIR, dir))) files.set(join(".gtm", dir, rel), readFileSync(join(KIT_DIR, dir, rel), "utf8"));
  }
  files.set(join(".gtm", "VERSION"), `${GTM_VERSION}\n`);
  files.set(
    join(".gtm", "README.md"),
    `# .gtm/\n\nCopied from ${PACKAGE_NAME} v${GTM_VERSION} by \`gtm sync\`. Read-only: CI fails if it differs from the\ninstalled version. To change anything here, open a PR in Veleads/gtm-core.\n`,
  );
  files.set("AGENTS.md", agentsMd());
  return files;
}

/** Returns the list of differences (empty = in sync). */
export function checkSync(root: string): string[] {
  const expected = expectedFiles();
  const diffs: string[] = [];
  for (const [rel, content] of expected) {
    const p = join(root, rel);
    if (!existsSync(p)) diffs.push(`missing  ${rel}`);
    else if (readFileSync(p, "utf8") !== content) diffs.push(`changed  ${rel}`);
  }
  if (existsSync(join(root, ".gtm"))) {
    for (const rel of walk(join(root, ".gtm"))) if (!expected.has(join(".gtm", rel))) diffs.push(`extra    ${join(".gtm", rel)}`);
  }
  const owners = expectedCodeowners(root);
  const ownersPath = join(root, CODEOWNERS);
  if (owners !== null && (existsSync(ownersPath) ? readFileSync(ownersPath, "utf8") : "") !== owners) diffs.push(`changed  ${CODEOWNERS} (gtm block)`);
  return diffs;
}

export function runSync(root: string, opts: { check?: boolean } = {}): boolean {
  if (opts.check) {
    const diffs = checkSync(root);
    if (diffs.length === 0) { console.log(`in sync with ${PACKAGE_NAME} v${GTM_VERSION}`); return true; }
    console.log(`out of sync with ${PACKAGE_NAME} v${GTM_VERSION} (run \`npx gtm sync\`; never edit .gtm/ or AGENTS.md by hand):`);
    for (const d of diffs) console.log(`  ${d}`);
    return false;
  }

  rmSync(join(root, ".gtm"), { recursive: true, force: true });
  for (const [rel, content] of expectedFiles()) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), content);
  }
  if (!existsSync(join(root, "CLAUDE.md"))) writeFileSync(join(root, "CLAUDE.md"), "@AGENTS.md\n");
  const owners = expectedCodeowners(root);
  if (owners !== null) {
    mkdirSync(join(root, ".github"), { recursive: true });
    writeFileSync(join(root, CODEOWNERS), owners);
  }
  console.log(`synced .gtm/ and AGENTS.md to ${PACKAGE_NAME} v${GTM_VERSION}`);
  return true;
}
